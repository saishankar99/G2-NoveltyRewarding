"""Generate a labeled golden dataset of submissions with Gemini.

Each submission responds to the fixed content and is tagged with a ground-truth
label so the evaluation tests have a known-correct answer:

  paraphrase -> near-duplicate of a common opinion (should score LOW novelty)
  novel      -> distinct on-topic angle          (should score HIGH novelty)
  offtopic   -> novel wording but irrelevant      (should be gated LOW)
  normal     -> ordinary on-topic comment

Usage:
    # Requires GEMINI_API_KEY in the environment.
    python data/generate_dataset.py --out data/submissions.generated.json

Without a key the script exits and you should use the committed
data/submissions.json, which is a deterministic fallback of the same shape.
"""

from __future__ import annotations

import argparse
import json
import os
from pathlib import Path

DATA_DIR = Path(__file__).resolve().parent

CATEGORY_PLAN = {
    "paraphrase": 13,
    "novel": 15,
    "offtopic": 10,
    "normal": 12,
}

CATEGORY_INSTRUCTIONS = {
    "paraphrase": (
        "Write near-duplicate opinions that all express the SAME single idea: "
        "'banning gas cars is great for cleaner air and a healthier city'. Vary "
        "only the wording slightly. These should feel repetitive and unoriginal."
    ),
    "novel": (
        "Each item must raise a DISTINCT, specific, rarely-mentioned angle about "
        "the gas-car ban (e.g. impact on independent mechanics, classic-car "
        "culture, the electrical grid, apartment dwellers, cold-weather range, "
        "used-car resale values, emergency fleets). No two items may overlap."
    ),
    "offtopic": (
        "Write about a completely UNRELATED hobby or topic (baking, "
        "astrophotography, knitting, chess, gardening, jazz, whale migration). "
        "The wording must be original and vivid but must NOT relate to cars, "
        "emissions, cities, or policy in any way."
    ),
    "normal": (
        "Write ordinary, on-topic reader comments reacting to the policy: mildly "
        "supportive, opposed, or neutral, referencing air quality, subsidies, "
        "charging, or affordability. Nothing especially original."
    ),
}


def _build_prompt(fixed_text: str, category: str, count: int) -> str:
    return (
        "You are generating synthetic reader submissions responding to this "
        f"fixed news item:\n\n\"{fixed_text}\"\n\n"
        f"Generate exactly {count} submissions. {CATEGORY_INSTRUCTIONS[category]}\n\n"
        "Return ONLY a JSON array. Each element must be an object with keys: "
        "\"headline\" (short string), \"body\" (1-2 sentences), and \"stance\" "
        "(one of \"Support\", \"Oppose\", \"Neutral\"). No markdown, no prose."
    )


def _generate_with_gemini(fixed_text: str) -> list[dict]:
    import google.generativeai as genai

    api_key = os.environ.get("GEMINI_API_KEY")
    if not api_key:
        raise SystemExit(
            "GEMINI_API_KEY not set. Use the committed data/submissions.json "
            "fallback, or export your key and re-run."
        )

    genai.configure(api_key=api_key)
    model = genai.GenerativeModel("gemini-2.5-flash")

    submissions: list[dict] = []
    idx = 1
    for category, count in CATEGORY_PLAN.items():
        prompt = _build_prompt(fixed_text, category, count)
        resp = model.generate_content(prompt)
        raw = resp.text.strip()
        if raw.startswith("```"):
            raw = raw.strip("`")
            raw = raw[raw.find("[") : raw.rfind("]") + 1]
        items = json.loads(raw)
        for item in items:
            submissions.append(
                {
                    "id": f"s{idx:02d}",
                    "label": category,
                    "stance": item.get("stance", "Neutral"),
                    "headline": item["headline"].strip(),
                    "body": item["body"].strip(),
                }
            )
            idx += 1
    return submissions


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--out",
        default=str(DATA_DIR / "submissions.generated.json"),
        help="Where to write the generated dataset.",
    )
    args = parser.parse_args()

    fixed = json.loads((DATA_DIR / "fixed_content.json").read_text(encoding="utf-8"))
    submissions = _generate_with_gemini(fixed["text"])

    payload = {
        "fixed_content_id": fixed["id"],
        "note": "Generated by Gemini. Labels are ground truth for evaluation.",
        "submissions": submissions,
    }
    Path(args.out).write_text(json.dumps(payload, indent=2), encoding="utf-8")
    print(f"Wrote {len(submissions)} submissions to {args.out}")


if __name__ == "__main__":
    main()
